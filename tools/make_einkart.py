"""Builds src/einkart_data.c from art/eink/eink-status-250x122.pbm (the status page's frame: mark, title and the
MODE:, GAMES:, GAME: labels) and art/eink/eink-mark-40.pbm (the title's 40x40 mark): both are the kernel's e-ink
layout already (1 bit a pixel, 1 = black, bit 7 leftmost, 32-byte rows / 5-byte rows)."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
def load(name, w, h):
    d = (ROOT / 'art/eink' / name).read_bytes(); n = 0; i = 0
    while n < 2: i = d.index(b'\n', i) + 1; n += 1
    b = d[i:]; assert d.startswith(b"P4\n") and len(b) == ((w + 7) // 8) * h, name; return b
def arr(name, b):
    out = [f'const uint8_t {name}[{len(b)}] = {{']
    for k in range(0, len(b), 24): out.append('  ' + ', '.join(str(x) for x in b[k:k + 24]) + ',')
    return out + ['};']
lines = ['/* SPDX-License-Identifier: MIT; generated by tools/make_einkart.py from the art/eink PBMs: do not edit. */', '#include "eink.h"']
lines += arr('ei_status_frame', load('eink-status-250x122.pbm', 250, 122)) + arr('ei_mark', load('eink-mark-40.pbm', 40, 40))
(ROOT / 'src/einkart_data.c').write_text('\n'.join(lines) + '\n')
