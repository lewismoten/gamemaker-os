"""Builds src/bootart_data.c from art/badge-96.png (Game-Maker OS boot art,
ChatGPT GPT-6.1 Sol from the maintainer's directions, MIT): the castle badge as a
palette (RGB565, rounded as src/rgb565.h) and run-length data, one byte a run (high nibble: palette index,
low nibble: run length - 1). No PNG decoder runs on the board."""
import pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parents[1]
im = Image.open(ROOT / 'art/badge-96.png').convert('RGB')
assert im.size == (96, 96)
pal = []
for p in im.getdata():
    if p not in pal: pal.append(p)
assert len(pal) <= 16
idx = [pal.index(p) for p in im.getdata()]
out = bytearray(); i = 0
while i < len(idx):
    n = 1
    while i + n < len(idx) and idx[i + n] == idx[i] and n < 16: n += 1
    out.append(idx[i] << 4 | n - 1); i += n
c565 = [(((r * 31 + 127) // 255) << 11) | (((g * 63 + 127) // 255) << 5) | ((b * 31 + 127) // 255) for r, g, b in pal]  # rounds as src/rgb565.h
lines = ['/* SPDX-License-Identifier: MIT; generated by tools/make_bootart.py from art/badge-96.png: do not edit. */',
         '#include "bootart.h"',
         'const uint16_t ba_pal[16] = {' + ', '.join(f'0x{c:04x}' for c in c565 + [0] * (16 - len(c565))) + '};',
         f'const uint16_t ba_rle_bytes = {len(out)};',
         'const uint8_t ba_rle[] = {']
for k in range(0, len(out), 24): lines.append('  ' + ', '.join(str(b) for b in out[k:k + 24]) + ',')
lines.append('};')
(ROOT / 'src/bootart_data.c').write_text('\n'.join(lines) + '\n')
print(len(out), 'bytes of runs,', len(pal), 'colors')
