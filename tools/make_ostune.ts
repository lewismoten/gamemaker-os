// Composes Game-Maker OS's own background tune in code: a calm 16-bar FM loop (about 45 s at 84 bpm) for the
// library, written as a .CMF with the Sandbox Edition's song tools (MIT) and embedded as src/ostune_data.c.
// Original: the melody, bass, pad and arpeggios are written here, after no existing song.
// Run from the Sandbox Edition's web/ folder:
//   GM_ROOT=<Sandbox Edition checkout> npx vite-node <this file> <out.cmf> <src/ostune_data.c>
import { writeFileSync } from 'node:fs';
const root = process.env.GM_ROOT!;
const { song } = await import(`${root}/web/packages/tools/src/music/compose`);
const { EPIANO, FLUTE, CELESTA, BASS } = await import(`${root}/web/packages/tools/src/kit/song`);
// One bar a chord: the tones the arpeggio walks (root, third, fifth) and the pad's held note.
const bars: { tones: [string, string, string]; pad: string; bass: string; tune: string }[] = [
  { tones: ['G4', 'B4', 'D5'], pad: 'D4', bass: 'G2 h, D3 h', tune: 'B4 q, D5 e, E5 e, D5 q, B4 q' },
  { tones: ['B4', 'D5', 'F#5'], pad: 'F#4', bass: 'B2 h, F#3 h', tune: 'D5 h, F#5 q, D5 q' },
  { tones: ['E4', 'G4', 'B4'], pad: 'G4', bass: 'E2 h, B2 h', tune: 'E5 q, G5 q, F#5 e, E5 e, D5 q' },
  { tones: ['C4', 'E4', 'G4'], pad: 'E4', bass: 'C3 h, G2 h', tune: 'E5 h, r e, G4 e, A4 q' },
  { tones: ['G4', 'B4', 'D5'], pad: 'D4', bass: 'G2 h, D3 h', tune: 'B4 q, D5 q, G5 h' },
  { tones: ['A4', 'C5', 'E5'], pad: 'E4', bass: 'A2 h, E3 h', tune: 'E5 q., D5 e, C5 q, A4 q' },
  { tones: ['D4', 'F#4', 'A4'], pad: 'F#4', bass: 'D3 h, A2 h', tune: 'F#5 e, E5 e, D5 e, C#5 e, D5 h' },
  { tones: ['D4', 'F#4', 'A4'], pad: 'F#4', bass: 'D3 w', tune: 'A4 h, r h' },
  { tones: ['C4', 'E4', 'G4'], pad: 'E4', bass: 'C3 h, G2 h', tune: 'G5 q, E5 q, C5 q, E5 q' },
  { tones: ['G4', 'B4', 'D5'], pad: 'D4', bass: 'G2 h, D3 h', tune: 'D5 q., B4 e, G4 h' },
  { tones: ['A4', 'C5', 'E5'], pad: 'E4', bass: 'A2 h, E3 h', tune: 'A4 e, C5 e, E5 q, D5 q, C5 q' },
  { tones: ['E4', 'G4', 'B4'], pad: 'G4', bass: 'E2 h, B2 h', tune: 'B4 h, G4 q, B4 q' },
  { tones: ['C4', 'E4', 'G4'], pad: 'E4', bass: 'C3 h, G2 h', tune: 'C5 q, E5 q, G5 q, E5 q' },
  { tones: ['D4', 'F#4', 'A4'], pad: 'F#4', bass: 'D3 h, A2 h', tune: 'F#5 q., E5 e, D5 q, A4 q' },
  { tones: ['G4', 'B4', 'D5'], pad: 'D4', bass: 'G2 h, D3 h', tune: 'B4 q, D5 q, E5 q, D5 q' },
  { tones: ['G4', 'B4', 'D5'], pad: 'D4', bass: 'G2 w', tune: 'G4 h, r h' },
];
const arp = (t: [string, string, string]) => [0, 1, 2, 1, 0, 1, 2, 1].map((i) => `${t[i]} e`).join(', ');
const cmf: Uint8Array = song(84, [
  { channel: 0, instrument: EPIANO, notes: bars.map((b) => b.tune).join(', '), velocity: 104 },
  { channel: 1, instrument: FLUTE, notes: bars.map((b) => `${b.pad} w`).join(', '), velocity: 62 },
  { channel: 2, instrument: BASS, notes: bars.map((b) => b.bass).join(', '), velocity: 88 },
  { channel: 3, instrument: CELESTA, notes: bars.map((b) => arp(b.tones)).join(', '), velocity: 58 },
]);
const [, , outCmf, outC] = process.argv;
writeFileSync(outCmf, cmf);
const rows: string[] = [];
for (let i = 0; i < cmf.length; i += 16) rows.push('  ' + Array.from(cmf.subarray(i, i + 16), (b) => b).join(', '));
writeFileSync(outC, `/* SPDX-License-Identifier: MIT; generated by tools/make_ostune.ts: Game-Maker OS's own tune, composed in code by Claude (Sonnet 5.5). */\n#include "ostune.h"\nconst uint8_t os_tune[${cmf.length}] = {\n${rows.join(',\n')}\n};\nconst uint32_t os_tune_len = ${cmf.length};\n`);
console.log(cmf.length, 'bytes');
