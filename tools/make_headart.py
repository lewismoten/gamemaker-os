"""Builds src/headart_data.c from art/header-badge-32.png (the maintainer's hand-drawn 32x32 castle favicon
frame): the games-list header badge as 2 bits a pixel (0 clear, 1 and 2 the palette in order of appearance,
RGB565 rounded as src/rgb565.h), 4 pixels a byte, first pixel in the high bits."""
import pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parents[1]
im = Image.open(ROOT / 'art/header-badge-32.png').convert('RGBA')
assert im.size == (32, 32)
pal = []; idx = []
for r, g, b, a in im.getdata():
    if a < 128: idx.append(0); continue
    if (r, g, b) not in pal: pal.append((r, g, b))
    idx.append(pal.index((r, g, b)) + 1)
assert len(pal) <= 3
c565 = [(((r * 31 + 127) // 255) << 11) | (((g * 63 + 127) // 255) << 5) | ((b * 31 + 127) // 255) for r, g, b in pal]
out = [idx[i] << 6 | idx[i + 1] << 4 | idx[i + 2] << 2 | idx[i + 3] for i in range(0, 1024, 4)]
lines = ['/* SPDX-License-Identifier: MIT; generated by tools/make_headart.py from art/header-badge-32.png: do not edit. */',
         '#include <stdint.h>',
         'const uint16_t ha_pal[4] = {0, ' + ', '.join(f'0x{c:04x}' for c in c565 + [0] * (3 - len(c565))) + '};',
         'const uint8_t ha_bits[256] = {']
for k in range(0, 256, 24): lines.append('  ' + ', '.join(str(b) for b in out[k:k + 24]) + ',')
lines.append('};')
(ROOT / 'src/headart_data.c').write_text('\n'.join(lines) + '\n')
