# Writes src/opl_tables.c: the lookup tables of the integer OPL2 port (src/opl.c).
# The constants are those of the Sandbox Edition web engine's audio/opl.ts and audio/cmfPlayer.ts
# (MIT), at 48 kHz. Run: python3 tools/make_opl_tables.py
import math
R = 48000.0
def rnd(x): return int(math.floor(x + 0.5))  # Math.round
sine = [rnd(math.sin((i + 0.5) / 256 * math.pi / 2) * 4095) for i in range(256)]
exp2 = [rnd(32768 * 2 ** (-i / 64)) for i in range(64)]
atk, dec = [], []
for rate in range(64):
    if rate < 4 or rate >= 60: atk.append(0)
    else:
        t = 2.826 / 2 ** ((rate - 4) / 4)
        atk.append(rnd(3.2 / (t * R) * 2 ** 31))
    if rate < 1: dec.append(0)
    else: dec.append(rnd(96 / (39.28 / 2 ** ((rate - 4) / 4)) / R * 2 ** 24))
dec[0] = 0
ksl = [rnd(v * 8) for v in [0, 9, 12, 13.875, 15, 16.125, 16.875, 17.625, 18, 18.75, 19.125, 19.5, 19.875, 20.25, 20.625, 21]]
note = []
for n in range(128):
    f = 440 * 2 ** ((n - 69) / 12)
    for block in range(8):
        fnum = rnd(f * 2 ** (20 - block) / 49716)
        if fnum < 1024: break
    block = min(block, 7); fnum = min(fnum, 1023)
    note.append(fnum | block << 10)
def arr(name, ty, v, per=12):
    rows = [", ".join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return f"const {ty} {name}[{len(v)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
out = "/* SPDX-License-Identifier: MIT; generated by tools/make_opl_tables.py, do not edit. */\n#include \"opl.h\"\n"
out += arr("opl_sine", "uint16_t", sine) + arr("opl_exp2", "uint16_t", exp2)
out += arr("opl_attack", "uint32_t", atk, 8) + arr("opl_decay", "uint32_t", dec, 8)
out += arr("opl_ksl", "uint8_t", ksl) + arr("opl_note", "uint16_t", note)
open("src/opl_tables.c", "w").write(out)
