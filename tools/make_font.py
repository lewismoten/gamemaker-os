"""Turn tools/font.txt into src/font_data.c (run after editing the font).
--check exits 1 if src/font_data.c is out of date."""
import pathlib, sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
def glyphs():
    out={}
    for line in (ROOT/'tools/font.txt').read_text().splitlines():
        if not line or line.startswith('//'): continue
        name,*rows=line.split(' ')
        ch=' ' if name=='space' else name
        assert len(ch)==1 and len(rows)==9 and all(len(r)==5 and set(r)<=set('#.') for r in rows),line
        out[ch]=[int(r.replace('#','1').replace('.','0'),2) for r in rows]
    assert sorted(out)==[chr(c) for c in range(32,127)],'need every printable ASCII character'
    return out
def source():
    g=glyphs();lines=['/* SPDX-License-Identifier: MIT; generated by tools/make_font.py from tools/font.txt. */',
                      '#include "font.h"','const uint8_t gm_font[95][9]={']
    for c in range(32,127):
        lines.append(' {'+','.join(f'0x{v:02x}' for v in g[chr(c)])+'}, /* '+('space' if c==32 else chr(c).replace('\\','backslash').replace('*','star'))+' */')
    return '\n'.join(lines+['};',''])
if __name__=='__main__':
    text=source();path=ROOT/'src/font_data.c'
    if '--check' in sys.argv: sys.exit(0 if path.exists() and path.read_text()==text else 1)
    path.write_text(text)
